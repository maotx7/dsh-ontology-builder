type Dict = typeof DICT.en
type Key = { [K in keyof Dict]: Dict[K] extends string ? K : never }[keyof Dict]

function format(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m))
}

const LangContext = createContext<[Lang, (l: Lang) => void]>(['en', () => {}])

export function LangProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => (localStorage.getItem(STORAGE_KEY) as Lang) || (navigator.language.startsWith('zh') ? 'zh' : 'en'))
  useEffect(() => localStorage.setItem(STORAGE_KEY, lang), [lang])
  return <LangContext.Provider value={[lang, setLang]}>{children}</LangContext.Provider>
}

export function useLang() {
  return useContext(LangContext)
}

/** Translate a string key, or look up a nested group (e.g. `t.group('tab')`). */
export function useT() {
  const [lang] = useContext(LangContext)
  const dict = DICT[lang]
  const t = (key: Key, vars?: Record<string, string | number>) => format(dict[key] as string, vars)
  t.tab = dict.tab
  return t
}
